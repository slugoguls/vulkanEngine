// Cube.cpp
#include "Cube.h"

Cube::Cube(float size) {
    float h = size / 2.0f;

    vertices = {
        // Front face
        {{-h, -h,  h}, {0, 0, 1}, {0.0f, 0.0f}},
        {{ h, -h,  h}, {0, 0, 1}, {1.0f, 0.0f}},
        {{ h,  h,  h}, {0, 0, 1}, {1.0f, 1.0f}},
        {{-h,  h,  h}, {0, 0, 1}, {0.0f, 1.0f}},
        // Back face
        {{-h, -h, -h}, {0, 0, -1}, {1.0f, 0.0f}},
        {{-h,  h, -h}, {0, 0, -1}, {1.0f, 1.0f}},
        {{ h,  h, -h}, {0, 0, -1}, {0.0f, 1.0f}},
        {{ h, -h, -h}, {0, 0, -1}, {0.0f, 0.0f}},
        // Left face
        {{-h, -h, -h}, {-1, 0, 0}, {0.0f, 0.0f}},
        {{-h, -h,  h}, {-1, 0, 0}, {1.0f, 0.0f}},
        {{-h,  h,  h}, {-1, 0, 0}, {1.0f, 1.0f}},
        {{-h,  h, -h}, {-1, 0, 0}, {0.0f, 1.0f}},
        // Right face
        {{ h, -h, -h}, {1, 0, 0}, {1.0f, 0.0f}},
        {{ h,  h, -h}, {1, 0, 0}, {1.0f, 1.0f}},
        {{ h,  h,  h}, {1, 0, 0}, {0.0f, 1.0f}},
        {{ h, -h,  h}, {1, 0, 0}, {0.0f, 0.0f}},
        // Top face
        {{-h,  h, -h}, {0, 1, 0}, {0.0f, 0.0f}},
        {{-h,  h,  h}, {0, 1, 0}, {0.0f, 1.0f}},
        {{ h,  h,  h}, {0, 1, 0}, {1.0f, 1.0f}},
        {{ h,  h, -h}, {0, 1, 0}, {1.0f, 0.0f}},
        // Bottom face
        {{-h, -h, -h}, {0, -1, 0}, {1.0f, 1.0f}},
        {{ h, -h, -h}, {0.0f, -1, 0}, {0.0f, 1.0f}},
        {{ h, -h,  h}, {0.0f, -1, 0}, {0.0f, 0.0f}},
        {{-h, -h,  h}, {0.0f, -1, 0}, {1.0f, 0.0f}},
    };

    indices = {
        0, 1, 2, 2, 3, 0,       // Front
        4, 5, 6, 6, 7, 4,       // Back
        8, 9, 10, 10, 11, 8,    // Left
        12, 13, 14, 14, 15, 12, // Right
        16, 17, 18, 18, 19, 16, // Top
        20, 21, 22, 22, 23, 20  // Bottom
    };
}
